const fs = require('fs');
const path = require('path');
const root = __dirname;
const mj = x => require(path.join(root, 'vendor/package/js', x));
const {mathjax} = mj('mathjax.js');
const {TeX} = mj('input/tex.js');
const {SVG} = mj('output/svg.js');
const {liteAdaptor} = mj('adaptors/liteAdaptor.js');
const {RegisterHTMLHandler} = mj('handlers/html.js');
const {STATE} = mj('core/MathItem.js');
const {SerializedMmlVisitor} = mj('core/MmlTree/SerializedMmlVisitor.js');
const packages = ['base','ams','newcommand','configmacros','mathtools','textmacros','bbox','boldsymbol','cancel','unicode','color'];
for (const p of packages) if (p !== 'base') mj('input/tex/'+p+'/'+({ams:'Ams',newcommand:'Newcommand',configmacros:'ConfigMacros',mathtools:'Mathtools',textmacros:'TextMacros',bbox:'Bbox',boldsymbol:'Boldsymbol',cancel:'Cancel',unicode:'Unicode',color:'Color'}[p])+'Configuration.js');
function normalize(text) {
  let s = text.trim().replace(/^```(?:latex|tex|math)?\s*\n?([\s\S]*?)\n?```$/i, '$1').trim();
  if (/^\\\\[[(]/.test(s)) s = s.replace(/\\\\(?=[A-Za-z()[\]{}])/g, '\\');
  for (const [a,b] of [['\\[','\\]'],['\\(','\\)'],['$$','$$'],['$','$']]) {
    if (s.startsWith(a) && s.endsWith(b)) {s = s.slice(a.length,-b.length).trim(); break;}
  }
  if (!s || s.length > 16000) throw Error('请输入公式，长度不得超过 16000 字符。');
  // Also spread batches generated by older versions, without changing explicit spacing.
  if (s.startsWith('\\begin{gathered}')) s=s.replace(/\\\\[ \t]*(?=\r?\n)/g,String.raw`\\[1.2em]`);
  return s;
}
async function main() {
  const request = JSON.parse(fs.readFileSync(process.argv[2], 'utf8').replace(/^\uFEFF/, ''));
  const latex = normalize(request.latex);
  const adaptor = liteAdaptor(); RegisterHTMLHandler(adaptor);
  const tex = new TeX({packages,
    formatError: (_jax, err) => {throw Error(err.message);}});
  const doc = mathjax.document('', {InputJax:tex, OutputJax:new SVG({fontCache:'none'})});
  let svg = adaptor.outerHTML(doc.convert(latex,{display:true,em:16,ex:8,containerWidth:16000}));
  svg = svg.slice(svg.indexOf('<svg'), svg.lastIndexOf('</svg>')+6);
  if (/data-mjx-error|data-mml-node="merror"/.test(svg)) throw Error('公式语法错误，请检查 LaTeX。');
  const vb = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  const pxPerEm = Number(request.fontPt || 14)*96/72;
  const width = Math.max(1,vb[2]/1000*pxPerEm), height=Math.max(1,vb[3]/1000*pxPerEm);
  svg=svg.replace(/\swidth="[^"]*"/, ` width="${width}px"`).replace(/\sheight="[^"]*"/, ` height="${height}px"`)
    .replace(/currentColor/g,'#000000');
  const base = request.outputBase;
  const mathml = new SerializedMmlVisitor().visitTree(doc.convert(latex,{display:true,end:STATE.CONVERT}));
  fs.writeFileSync(base+'.mml', mathml);
  fs.writeFileSync(base+'.svg',svg);
  const config = JSON.parse(fs.readFileSync(path.join(root,'runtime.json'),'utf8'));
  const sharp = require(path.resolve(root,config.modules,'sharp'));
  await sharp(Buffer.from(svg),{density:192}).png().toFile(base+'.png');
  fs.writeFileSync(base+'.json',JSON.stringify({latex,width,height,svg:base+'.svg',png:base+'.png',mathml:base+'.mml'}));
}
main().catch(e=>{process.stderr.write(e.message+'\n');process.exitCode=1;});
